// Generates src/data/ganapatiTarpanam.js from the tarpaṇam litany in the
// ganapati-caturavrutti-tarpanam.mdx doc, so the interactive TarpanamGuide
// always stays in exact sync with the written text (single source of truth).
//
// Run:  node scripts/gen-tarpanam-data.js

const fs = require('fs');
const path = require('path');

const MDX = path.join(
  __dirname,
  '..',
  'docs',
  'ganapati',
  'ganapati-caturavrutti-tarpanam.mdx'
);
const OUT = path.join(__dirname, '..', 'src', 'data', 'ganapatiTarpanam.js');

const src = fs.readFileSync(MDX, 'utf8');

// Isolate the "## తర్పణం · Tarpaṇa (444 counts)" section.
const startMatch = src.match(/##\s*[^\n]*Tarpa[nṇ]a\s*\(444/);
if (!startMatch) throw new Error('Could not locate the Tarpaṇa (444 counts) heading.');
const startIdx = startMatch.index;
const rest = src.slice(startIdx);
// End at the next top-level heading after this one.
const endRel = rest.search(/\n##\s+[^#]/);
const section = endRel === -1 ? rest : rest.slice(0, endRel);

const lineRe = /<LinePair\s+te="([\s\S]*?)"\s+en="([\s\S]*?)"\s*\/>/g;

// Strip the trailing "| (repeat-word) | <cumulative>" bookkeeping so the guide
// shows only the mantra that is actually recited.
function cleanTe(s) {
  return s
    .replace(/\s*\|\s*\((?:ద్వాదశవారం|చతుర్వారం)\)\s*\|\s*\d+\s*$/u, '')
    .trim();
}
function cleanEn(s) {
  return s
    .replace(/\s*\|\s*\((?:dvādaśavāraṁ|caturvāraṁ)\)\s*\|\s*\d+\s*$/u, '')
    .replace(/&quot;/g, '"')
    .trim();
}

const steps = [];
let prevCount = 0;
let m;
while ((m = lineRe.exec(section)) !== null) {
  const rawTe = m[1];
  const rawEn = m[2];
  const countMatch = rawEn.match(/\|\s*(\d+)\s*$/);
  if (!countMatch) continue; // skip any non-count line defensively
  const cumulative = parseInt(countMatch[1], 10);
  const reps = cumulative - prevCount;
  prevCount = cumulative;
  steps.push({
    te: cleanTe(rawTe),
    en: cleanEn(rawEn),
    reps,
    cumulative,
  });
}

if (steps.length === 0) throw new Error('No tarpaṇam lines were parsed.');
const total = steps[steps.length - 1].cumulative;

const banner = `// AUTO-GENERATED by scripts/gen-tarpanam-data.js — do not edit by hand.
// Source: docs/ganapati/ganapati-caturavrutti-tarpanam.mdx (Tarpaṇa section).
// Regenerate with:  node scripts/gen-tarpanam-data.js
`;

const body =
  banner +
  `\nexport const TARPANAM_TOTAL = ${total};\n` +
  `\nexport const TARPANAM_STEPS = ${JSON.stringify(steps, null, 2)};\n` +
  `\nexport default TARPANAM_STEPS;\n`;

fs.writeFileSync(OUT, body, 'utf8');
console.log(
  `Wrote ${steps.length} steps (total ${total} counts) -> ${path.relative(
    path.join(__dirname, '..'),
    OUT
  )}`
);
