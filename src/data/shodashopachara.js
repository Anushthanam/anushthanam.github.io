// Common helper used in almost every step: "oṃ [dative] namaḥ | <action>".
const namah = (d, action_te, action_iast) => ({
  te:   `ఓం ${d.dative_te} నమః | ${action_te}`,
  iast: `oṃ ${d.dative_iast} namaḥ | ${action_iast}`,
});

